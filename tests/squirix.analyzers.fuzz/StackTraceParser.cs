using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Text.RegularExpressions;

namespace Squirix.Analyzers.Fuzz;

/// <summary>Extracts the frames of the analyzers from the text of an exception, or from the output of a process that crashed (e.g. "Stack overflow.").</summary>
internal static partial class StackTraceParser
{
    public static ImmutableArray<string> GetAnalyzerFrames(string text)
    {
        var frames = ImmutableArray.CreateBuilder<string>();
        foreach (Match match in FrameRegex().Matches(text))
        {
            var method = match.Groups["method"].Value.Trim();
            if (IsAnalyzerFrame(method))
                frames.Add(Normalize(method));
        }

        return frames.ToImmutable();
    }

    /// <summary>The first frames of the first stack trace of the text, where the exception is thrown, normalized.</summary>
    public static ImmutableArray<string> GetTopFrames(string text, int maxCount)
    {
        var frames = ImmutableArray.CreateBuilder<string>();
        foreach (Match match in FrameRegex().Matches(text))
        {
            if (frames.Count >= maxCount)
                break;

            frames.Add(Normalize(match.Groups["method"].Value.Trim()));
        }

        return frames.ToImmutable();
    }

    /// <summary>The lines of the text that are stack frames, at most <paramref name="maxCount" />, with the consecutive duplicates of a stack overflow collapsed.</summary>
    public static string GetFrameLines(string text, int maxCount)
    {
        var lines = new List<string>();
        string? previous = null;
        var repeatCount = 0;
        foreach (Match match in FrameRegex().Matches(text))
        {
            var line = match.Value.TrimEnd();
            if (line == previous)
            {
                repeatCount++;
                continue;
            }

            AddRepeatCount(lines, ref repeatCount);
            if (lines.Count >= maxCount)
                break;

            lines.Add(line);
            previous = line;
        }

        AddRepeatCount(lines, ref repeatCount);
        return string.Join('\n', lines);
    }

    private static void AddRepeatCount(List<string> lines, ref int repeatCount)
    {
        if (repeatCount == 0)
            return;

        lines.Add($"   ... repeated {repeatCount.ToString(CultureInfo.InvariantCulture)} more times");
        repeatCount = 0;
    }

    [GeneratedRegex("[0-9]+", RegexOptions.None, 10_000)]
    private static partial Regex DigitsRegex();

    [GeneratedRegex(@"^[ \t]*at (?<method>[^(\r\n]+)\(.*$", RegexOptions.Multiline | RegexOptions.ExplicitCapture, 10_000)]
    private static partial Regex FrameRegex();

    private static bool IsAnalyzerFrame(string method) =>
        method.StartsWith("Squirix.Analyzers.", StringComparison.Ordinal) && !method.StartsWith("Squirix.Analyzers.Fuzz.", StringComparison.Ordinal);

    // The names generated by the compiler for the lambdas, the local functions and the state machines contain
    // ordinals that change when the code is edited, so they are removed to keep the signatures of the findings stable
    private static string Normalize(string method)
    {
        var segments = method.Split('.');
        for (var index = 0; index < segments.Length; index++)
        {
            if (segments[index].AsSpan().IndexOfAny('<', '>', '|') >= 0)
                segments[index] = DigitsRegex().Replace(segments[index], "");
        }

        return string.Join('.', segments);
    }
}

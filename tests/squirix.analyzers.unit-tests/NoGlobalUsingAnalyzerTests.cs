using System.Threading;
using System.Threading.Tasks;
using Squirix.Analyzers.UnitTests.Support;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;

namespace Squirix.Analyzers.UnitTests;

public sealed class NoGlobalUsingAnalyzerTests
{
    private const string RuleId = "SQR0034";

    [Test]
    public async Task AllowsFileLocalUsingDirective(CancellationToken cancellationToken)
    {
        const string source = """
                              using System;

                              namespace Acme
                              {
                                  class Cache
                                  {
                                  }
                              }
                              """;

        var diagnostics = await AnalyzerRunner.RunAsync(new NoGlobalUsingAnalyzer(), source, cancellationToken);

        _ = await Assert.That(diagnostics).IsEmpty();
    }

    [Test]
    public async Task FlagsGlobalUsingDirective(CancellationToken cancellationToken)
    {
        const string source = """
                              global using System;

                              namespace Acme
                              {
                                  class Cache
                                  {
                                  }
                              }
                              """;

        var diagnostics = await AnalyzerRunner.RunAsync(new NoGlobalUsingAnalyzer(), source, cancellationToken);

        var diagnostic = await Assert.That(diagnostics).HasSingleItem();
        _ = await Assert.That(diagnostic.Id).IsEqualTo(RuleId);
    }

    [Test]
    public async Task FlagsGlobalStaticUsingDirective(CancellationToken cancellationToken)
    {
        const string source = """
                              global using static System.Math;

                              namespace Acme
                              {
                                  class Cache
                                  {
                                  }
                              }
                              """;

        var diagnostics = await AnalyzerRunner.RunAsync(new NoGlobalUsingAnalyzer(), source, cancellationToken);

        var diagnostic = await Assert.That(diagnostics).HasSingleItem();
        _ = await Assert.That(diagnostic.Id).IsEqualTo(RuleId);
    }

    [Test]
    public async Task FlagsImplicitUsingsGeneratedGlobalUsing(CancellationToken cancellationToken)
    {
        const string source = """
                              // <auto-generated/>
                              global using System;

                              namespace Acme
                              {
                                  class Cache
                                  {
                                  }
                              }
                              """;

        var diagnostics = await AnalyzerRunner.RunAsync(new NoGlobalUsingAnalyzer(), source, cancellationToken);

        var diagnostic = await Assert.That(diagnostics).HasSingleItem();
        _ = await Assert.That(diagnostic.Id).IsEqualTo(RuleId);
    }
}
